"""rk_report -- self-contained auxiliary HTML report (plan 4.7, D8).

report --run DIR -> <run_dir>/aux_report.html (no external links/scripts),
                    run.json "aux_report" + "official_reports"

Contents: run conditions (test, corners, life, windows, RelStudio version,
Work_Dir), the per-corner result summary, aging worst devices, DEOS
violations (or top DPM devices), EMIR summary, and where RelStudio's own
official reports are (D8: the official report is RelStudio's; this one is
only an aid).

Python 3.8+, stdlib only.
"""

import html
import os

import rk_common

TOP_N = 20


def esc(v):
    if v is None:
        return ""
    if isinstance(v, float):
        return html.escape("%.4g" % v)
    return html.escape(str(v))


def read_tsv(path, limit=None):
    if not path or not os.path.isfile(path):
        return [], []
    with open(path, "r", encoding="utf-8") as f:
        lines = f.read().splitlines()
    if not lines:
        return [], []
    header = lines[0].split("\t")
    rows = [l.split("\t") for l in lines[1:]]
    return header, rows[:limit] if limit else rows


def table(header, rows, sev_col=None, cls=""):
    out = ['<table class="%s"><thead><tr>' % cls]
    out += ["<th>%s</th>" % esc(h) for h in header]
    out.append("</tr></thead><tbody>")
    for r in rows:
        sev = r[sev_col] if sev_col is not None and sev_col < len(r) else ""
        out.append('<tr class="%s">' % esc(sev))
        out += ["<td>%s</td>" % esc(v) for v in r]
        out.append("</tr>")
    out.append("</tbody></table>")
    return "".join(out)


